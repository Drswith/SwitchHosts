// swift-tools-version:5.9
import PackageDescription

// `scripts/build-core.sh` builds the Rust core into crates/swh-ffi/target.
// Context.packageDirectory keeps the path absolute for the linker.
let rustLibDir = "\(Context.packageDirectory)/../../crates/swh-ffi/target/release"

let package = Package(
    name: "SwitchHostsNative",
    defaultLocalization: "en",
    platforms: [.macOS(.v13)],
    products: [
        .executable(name: "SwitchHostsNative", targets: ["SwitchHostsNative"]),
    ],
    targets: [
        // C declarations for crates/swh-ffi/include/swh.h.
        .target(
            name: "CSwhFFI",
            path: "Sources/CSwhFFI",
            publicHeadersPath: "include"
        ),
        // Swift wrapper over the C ABI. Links the Rust static library.
        .target(
            name: "SwitchHostsCore",
            dependencies: ["CSwhFFI"],
            path: "Sources/SwitchHostsCore",
            linkerSettings: [
                .unsafeFlags(["-L", rustLibDir]),
                .linkedLibrary("swh_ffi"),
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                .linkedFramework("SystemConfiguration"),
                .linkedFramework("ServiceManagement"),
            ]
        ),
        .executableTarget(
            name: "SwitchHostsNative",
            dependencies: ["SwitchHostsCore"],
            path: "Sources/SwitchHostsNative",
            // Localizable.strings per language, generated by scripts/sync-localizations.py.
            resources: [.process("Resources")]
        ),
        .testTarget(
            name: "SwitchHostsCoreTests",
            dependencies: ["SwitchHostsCore", "SwitchHostsNative"],
            path: "Tests/SwitchHostsCoreTests"
        ),
    ]
)
